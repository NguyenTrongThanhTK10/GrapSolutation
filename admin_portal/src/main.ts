import { createApp } from 'vue';
import PrimeVue from 'primevue/config';
import Aura from '@primeuix/themes/aura';
import { definePreset } from '@primeuix/themes';
import ToastService from 'primevue/toastservice';
import ConfirmationService from 'primevue/confirmationservice';
import Tooltip from 'primevue/tooltip';
import { createRouter, createWebHistory } from 'vue-router';
import App from './App.vue';
import { currentUser } from './lib/api';
import { canAccess, homeFor } from './lib/access';
const Forbidden = () => import('./views/Forbidden.vue');
const Dashboard = () => import('./views/Dashboard.vue');
const Rides = () => import('./views/Rides.vue');
const Drivers = () => import('./views/Drivers.vue');
const Customers = () => import('./views/Customers.vue');
const Pricing = () => import('./views/Pricing.vue');
const Finance = () => import('./views/Finance.vue');
const Support = () => import('./views/Support.vue');
const Audit = () => import('./views/Audit.vue');
const Settings = () => import('./views/Settings.vue');
const Sandbox = () => import('./views/Sandbox.vue');
const Share = () => import('./views/Share.vue');
import 'primeicons/primeicons.css';
import 'leaflet/dist/leaflet.css';
import './style.css';
const preset = definePreset(Aura, { semantic: { primary: { 50: '#effcf5', 100: '#d9f5e5', 200: '#b4e9cf', 300: '#7fd5b0', 400: '#42b88a', 500: '#159367', 600: '#087f55', 700: '#096646', 800: '#0d513a', 900: '#0c4231', 950: '#03271d' } } });
const router = createRouter({ history: createWebHistory(), routes: [ { path: '/forbidden', component: Forbidden, meta: { title: 'Quyền truy cập' } }, { path: '/share/:token', component: Share, meta: { title: 'Chia sẻ hành trình' } }, { path: '/', component: Dashboard, meta: { title: 'Tổng quan' } }, { path: '/rides', component: Rides, meta: { title: 'Quản lý chuyến xe' } }, { path: '/dispatch', component: Rides, meta: { title: 'Điều phối trực tiếp' } }, { path: '/drivers', component: Drivers, meta: { title: 'Đối tác tài xế' } }, { path: '/customers', component: Customers, meta: { title: 'Khách hàng' } }, { path: '/pricing', component: Pricing, meta: { title: 'Giá cước & vùng dịch vụ' } }, { path: '/finance', component: Finance, meta: { title: 'Tài chính & đối soát' } }, { path: '/support', component: Support, meta: { title: 'Trung tâm hỗ trợ' } }, { path: '/audit', component: Audit, meta: { title: 'Nhật ký hoạt động' } }, { path: '/settings', component: Settings, meta: { title: 'Cấu hình hệ thống' } }, { path: '/customer', component: Sandbox, meta: { title: 'Trải nghiệm khách hàng' } }, { path: '/driver', component: Sandbox, meta: { title: 'Trải nghiệm tài xế' } }, { path: '/:pathMatch(.*)*', redirect: '/' } ], scrollBehavior: () => ({ top: 0 }) });
router.beforeEach(to => {
  if (!currentUser.value || to.path.startsWith('/share/') || to.path === '/forbidden') return true;
  if (to.path === '/' && ['Customer', 'Driver'].includes(currentUser.value.role)) return homeFor(currentUser.value.role);
  return canAccess(to.path, currentUser.value.role) ? true : '/forbidden';
});
router.afterEach(to => { document.title = `${String(to.meta.title ?? 'Grap')} · Grap Console`; });
createApp(App).use(router).use(PrimeVue, { theme: { preset, options: { darkModeSelector: '.grap-dark' } }, ripple: true, pt: { datatable: { tableContainer: { tabindex: 0, role: 'region', 'aria-label': 'Bảng dữ liệu; cuộn ngang để xem thêm cột' } } } }).use(ToastService).use(ConfirmationService).directive('tooltip', Tooltip).mount('#app');
